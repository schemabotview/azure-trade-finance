"""Write TradeBook's data and the risk team's reference files.

  python -m tradebook_gen --out data                   everything
  python -m tradebook_gen --out data --part tradebook  only TradeBook (the source system)
  python -m tradebook_gen verify                       assert every planted fact

Same seed → byte-identical files. Layout under --out:

  tradebook/counterparties.csv       TradeBook's applicants (legal entities, no groups)
  tradebook/lc_deals.csv             each LC's current row at 02:00 on the business date
  tradebook/lc_amendments.csv        every version up to then: the history behind lc_deals
  tradebook/desk-2026-10-31.sql      the desk's business day, as the statements its app ran
  tradebook/desk-late.sql            §5.6's three amendments at 02:00:07, during batch 42's copy
  reference/counterparty_group.csv   the risk team's mapping: counterparty → group
  reference/group_limits.csv         each group's limit per currency
"""
from __future__ import annotations

import argparse
import csv
import io
import sys
from decimal import Decimal
from pathlib import Path

from .model import (BUSINESS_DATE, CORRECTION_BAD_AMOUNT, CORRECTION_BAD_KEY_LC, CORRECTION_BATCH, COUNTERPARTIES,
                    LATE_AMENDED, LATE_AT, SEED_CUTOFF, WINDOW_END, build, counterparty_group_rows, group_limit_rows)

PARTS = ('tradebook', 'reference', 'deliveries')


def ts(t) -> str:
    return t.strftime('%Y-%m-%d %H:%M:%S+00')


def csv_text(rows: list[dict]) -> str:
    buf = io.StringIO(newline='')
    w = csv.DictWriter(buf, fieldnames=list(rows[0]), lineterminator='\n')
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


def lit(v) -> str:
    return str(v) if isinstance(v, (int, Decimal)) else "'" + str(v).replace("'", "''") + "'"


COLUMNS = {'lc_id': 'text', 'applicant_id': 'text', 'beneficiary': 'text', 'currency': 'character(3)', 'amount': 'numeric(18,2)',
           'status': 'text', 'issue_date': 'date', 'expiry_date': 'date', 'source_version': 'integer',
           'updated_at': 'timestamp with time zone'}


def correction() -> dict[str, str]:
    """Batch 43: the desk's manual correction file — the three late amendments, as extract.py writes rows,
    plus two rows typed by hand: one with its lc_id cell empty, one with the amount written 2,0m."""
    import json
    lcs = {lc.lc_id: lc for lc in build()}
    row = lambda lc_id, v, at: [lc_id, lcs[lc_id].applicant_id, lcs[lc_id].beneficiary, lcs[lc_id].currency, f'{v.amount:.2f}', v.status,
                                lcs[lc_id].issue_date.isoformat(), lcs[lc_id].expiry_date.isoformat(), str(v.version), at]
    stamp = LATE_AT.strftime('%Y-%m-%d %H:%M:%S+00:00')
    rows = []
    for lc_id in LATE_AMENDED:
        v = lcs[lc_id].versions[-1]
        late = type(v)(v.version + 1, v.amount + Decimal('25000.00'), 'AMENDED', LATE_AT)
        rows.append(row(lc_id, late, stamp))
    blank = row(CORRECTION_BAD_KEY_LC, lcs[CORRECTION_BAD_KEY_LC].at(WINDOW_END), stamp)
    blank[0] = ''
    typo = row('LC-2401', lcs['LC-2401'].at(WINDOW_END), stamp)
    typo[4] = CORRECTION_BAD_AMOUNT
    rows += [blank, typo]
    buf = io.StringIO(newline='')
    w = csv.writer(buf, lineterminator='\n')
    w.writerow(list(COLUMNS))
    w.writerows(rows)
    manifest = {'batch_id': CORRECTION_BATCH, 'table': 'lc_deals', 'source': 'manual correction, trade finance operations',
                'expected_rows': len(rows), 'files': ['part-00000.csv'], 'columns': COLUMNS}
    return {f'batch_id={CORRECTION_BATCH}/part-00000.csv': buf.getvalue(),
            f'batch_id={CORRECTION_BATCH}/_manifest.json': json.dumps(manifest, indent=2)}


def files(part: str) -> dict[str, str]:
    """Every file of a part, {relative path: text}."""
    if part == 'deliveries':
        return correction()
    if part == 'reference':
        return {'counterparty_group.csv': csv_text(counterparty_group_rows()), 'group_limits.csv': csv_text(group_limit_rows())}
    lcs = build()
    seed = [(lc, lc.at(SEED_CUTOFF)) for lc in lcs]
    deals = [{'lc_id': lc.lc_id, 'applicant_id': lc.applicant_id, 'beneficiary': lc.beneficiary, 'currency': lc.currency,
              'amount': f'{v.amount:.2f}', 'status': v.status, 'issue_date': lc.issue_date.isoformat(),
              'expiry_date': lc.expiry_date.isoformat(), 'source_version': v.version, 'updated_at': ts(v.at)}
             for lc, v in seed if v]
    history = [{'lc_id': lc.lc_id, 'source_version': v.version, 'amount': f'{v.amount:.2f}', 'status': v.status, 'changed_at': ts(v.at)}
               for lc in lcs for v in lc.versions if v.at <= SEED_CUTOFF]
    day = sorted(((v.at, lc, v) for lc in lcs for v in lc.versions if v.at > SEED_CUTOFF), key=lambda t: (t[0], t[1].lc_id))
    sql = [f'-- The trade finance desk\'s business day, {BUSINESS_DATE}: every change its application made to',
           '-- TradeBook, in order. Generated by tradebook_gen; applied between batch 41 and batch 42.', 'BEGIN;']
    for at, lc, v in day:
        if v.version == 1:
            cols = 'lc_id, applicant_id, beneficiary, currency, amount, status, issue_date, expiry_date, source_version, updated_at'
            vals = [lc.lc_id, lc.applicant_id, lc.beneficiary, lc.currency, Decimal(f'{v.amount:.2f}'), v.status,
                    lc.issue_date.isoformat(), lc.expiry_date.isoformat(), v.version, ts(at)]
            sql.append(f'INSERT INTO lc_deals ({cols}) VALUES ({", ".join(map(lit, vals))});')
        else:
            sql.append(f"UPDATE lc_deals SET amount = {v.amount:.2f}, status = '{v.status}', source_version = {v.version}, "
                       f"updated_at = '{ts(at)}' WHERE lc_id = '{lc.lc_id}';")
        sql.append(f"INSERT INTO lc_amendments VALUES ('{lc.lc_id}', {v.version}, {v.amount:.2f}, '{v.status}', '{ts(at)}');")
    sql.append('COMMIT;')
    late = ['-- 02:00:07 on 1 November: the desk amends three LCs while batch 42 is copying (§5.6).', 'BEGIN;']
    for lc in (x for x in lcs if x.lc_id in LATE_AMENDED):
        v = lc.versions[-1]
        amt = v.amount + Decimal('25000.00')
        late.append(f"UPDATE lc_deals SET amount = {amt:.2f}, status = 'AMENDED', source_version = {v.version + 1}, "
                    f"updated_at = '{ts(LATE_AT)}' WHERE lc_id = '{lc.lc_id}';")
        late.append(f"INSERT INTO lc_amendments VALUES ('{lc.lc_id}', {v.version + 1}, {amt:.2f}, 'AMENDED', '{ts(LATE_AT)}');")
    late.append('COMMIT;')
    return {
        'counterparties.csv': csv_text([{'counterparty_id': c, 'name': n, 'country': k} for c, n, k, _ in COUNTERPARTIES]),
        'lc_deals.csv': csv_text(deals),
        'lc_amendments.csv': csv_text(history),
        f'desk-{BUSINESS_DATE}.sql': '\n'.join(sql) + '\n',
        'desk-late.sql': '\n'.join(late) + '\n',
    }


def main(argv: list[str]) -> int:
    if argv[:1] == ['verify']:
        from .verify import verify
        return verify()
    p = argparse.ArgumentParser(prog='tradebook_gen')
    p.add_argument('--out', required=True, type=Path)
    p.add_argument('--part', choices=PARTS, action='append')
    a = p.parse_args(argv)
    for part in a.part or PARTS:
        for name, text in files(part).items():
            path = a.out / part / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
